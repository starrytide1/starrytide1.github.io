var GENERIC = ['他', '她', '男人', '女人', '这个人', '那个人', '是否', '难道', '会不会', '请问', '那个'];

function expand(raw, i) {
  var num = String(i + 1);
  while (num.length < 3) num = '0' + num;
  var yesFacts = raw.f.filter(function (f) { return f[1] === '是'; });
  return {
    id: '汤 No.' + num,
    title: raw.t,
    prompt: raw.p,
    answer: raw.a,
    quick: raw.q,
    rules: raw.f.map(function (f) {
      return { keys: f[0], v: f[1], clue: f[2] || '' };
    }),
    keyPoints: yesFacts.map(function (f) { return { keys: f[0] }; }),
    answerPoints: yesFacts.map(function (f) {
      var words = f[0].filter(function (w) { return GENERIC.indexOf(w) === -1; });
      return {
        label: f[3],
        groups: [words.length ? words : f[0]],
        hint: '「' + f[3] + '」这一环，好像还差一点。'
      };
    })
  };
}

export const SOUP_LIBRARY = RAW.map(expand);
export default SOUP_LIBRARY;
